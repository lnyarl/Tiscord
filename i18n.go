var messageCatalogs = map[string]map[string]string{
	"ko":    koreanMessages,
	"ja":    japaneseMessages,
	"zh-CN": chineseMessages,
	"es":    spanishMessages,
	"de":    germanMessages,
}

func localize(language, message string, args ...any) string {
	if translated, ok := messageCatalogs[language][message]; ok {
		message = translated
	}
	if len(args) > 0 {
		return fmt.Sprintf(message, args...)
	}
	return message
}
func (m *model) tr(message string, args ...any) string {
	return localize(m.config.Behavior.Language, message, args...)
}
